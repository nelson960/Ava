from __future__ import annotations

from collections import defaultdict
from enum import StrEnum
from typing import Annotated

from pydantic import Field, StringConstraints, model_validator

from ..canvas.protocol import (
    CANVAS_MAX_NODES_PER_TURN,
    CANVAS_MAX_TRANSACTIONS_PER_TURN,
    AvaCanvasTransaction,
    CanvasCreateOperation,
)
from .common import NodeIdentifier, NonEmptyText, RealtimeProtocolModel


MAX_REALTIME_SPEECH_SEGMENTS = 12


class AvaDelivery(StrEnum):
    NEUTRAL = "neutral"
    WARM = "warm"
    PLAYFUL = "playful"
    THOUGHTFUL = "thoughtful"
    ENCOURAGING = "encouraging"
    CONCERNED = "concerned"


class AvaExpressionIntent(StrEnum):
    NEUTRAL = "neutral"
    WARM_SMILE = "warmSmile"
    CURIOUS = "curious"
    THINKING = "thinking"
    ENCOURAGING = "encouraging"
    CONCERNED = "concerned"
    SERIOUS = "serious"


class AvaGazeIntent(StrEnum):
    CHILD = "child"
    THINKING_AWAY = "thinkingAway"
    CANVAS = "canvas"


class AvaMotionIntent(StrEnum):
    NONE = "none"
    ACKNOWLEDGE = "acknowledge"
    PRESENT_CANVAS = "presentCanvas"
    ENCOURAGE = "encourage"


class CanvasComplexity(StrEnum):
    NONE = "none"
    NORMAL = "normal"
    SPECIALIST_REQUIRED = "specialistRequired"


class MemoryProposalKind(StrEnum):
    INTEREST = "interest"
    PREFERENCE = "preference"


SegmentIdentifier = Annotated[
    str,
    StringConstraints(
        strip_whitespace=True,
        min_length=1,
        max_length=40,
        pattern=r"^[a-z][a-z0-9_]*$",
    ),
]


class AvaPhraseAnchor(RealtimeProtocolModel):
    phrase: Annotated[NonEmptyText, StringConstraints(max_length=120)]
    occurrence: int = Field(ge=0, le=3)


class AvaCanvasCue(RealtimeProtocolModel):
    id: NodeIdentifier
    anchor: AvaPhraseAnchor
    transaction: AvaCanvasTransaction


class AvaTurnSegment(RealtimeProtocolModel):
    id: SegmentIdentifier
    speech: Annotated[NonEmptyText, StringConstraints(max_length=600)]
    delivery: AvaDelivery
    expression: AvaExpressionIntent
    gaze: AvaGazeIntent
    motion_intent: AvaMotionIntent
    canvas_cues: list[AvaCanvasCue] = Field(
        max_length=4,
        description=(
            "Timed scene transactions, not individual visual objects. Put all "
            "initial nodes and bindings in one transaction's operations."
        ),
    )

    @model_validator(mode="after")
    def semantic_cues_are_coherent(self) -> AvaTurnSegment:
        has_canvas = bool(self.canvas_cues)
        if (self.gaze == AvaGazeIntent.CANVAS) != has_canvas:
            raise ValueError("gaze=canvas requires canvasCues and vice versa")
        if (self.motion_intent == AvaMotionIntent.PRESENT_CANVAS) != has_canvas:
            raise ValueError(
                "motionIntent=presentCanvas requires canvasCues and vice versa"
            )

        cue_ids = [cue.id for cue in self.canvas_cues]
        if len(cue_ids) != len(set(cue_ids)):
            raise ValueError("canvas cue ids must be unique per segment")

        for cue in self.canvas_cues:
            positions = _substring_positions(self.speech, cue.anchor.phrase)
            if cue.anchor.occurrence >= len(positions):
                raise ValueError(
                    f"canvas cue anchor phrase {cue.anchor.phrase!r} occurrence "
                    f"{cue.anchor.occurrence} is not present in segment speech"
                )
        return self


class AvaMemoryProposal(RealtimeProtocolModel):
    kind: MemoryProposalKind
    summary: Annotated[NonEmptyText, StringConstraints(max_length=160)]
    evidence: Annotated[NonEmptyText, StringConstraints(max_length=160)]
    confidence: float = Field(ge=0, le=1, allow_inf_nan=False)


class AvaCanvasDecision(RealtimeProtocolModel):
    complexity: CanvasComplexity
    specialist_brief: Annotated[NonEmptyText, StringConstraints(max_length=500)] | None

    @model_validator(mode="after")
    def specialist_brief_matches_complexity(self) -> AvaCanvasDecision:
        needs_specialist = self.complexity == CanvasComplexity.SPECIALIST_REQUIRED
        if needs_specialist != (self.specialist_brief is not None):
            raise ValueError("specialistBrief is required only for specialistRequired")
        return self


class AvaTurnPlan(RealtimeProtocolModel):
    """Internal delivered-turn record built from assistant text and tool state.

    This is not sent to or generated by Realtime. It keeps the existing speech,
    sample-clock, canvas, and memory boundaries coherent inside Ava.
    """

    segments: list[AvaTurnSegment] = Field(
        min_length=1,
        max_length=MAX_REALTIME_SPEECH_SEGMENTS,
    )
    memory_proposal: AvaMemoryProposal | None
    child_turn_summary: Annotated[NonEmptyText, StringConstraints(max_length=240)]
    canvas_decision: AvaCanvasDecision

    @model_validator(mode="after")
    def plan_is_bounded_and_coherent(self) -> AvaTurnPlan:
        segment_ids = [segment.id for segment in self.segments]
        if len(segment_ids) != len(set(segment_ids)):
            raise ValueError("turn segment ids must be unique")

        joined_speech = " ".join(segment.speech for segment in self.segments)
        if len(joined_speech) > 1_800:
            raise ValueError("turn speech exceeds the 1800-character limit")

        cues = [cue for segment in self.segments for cue in segment.canvas_cues]
        if len(cues) > CANVAS_MAX_TRANSACTIONS_PER_TURN:
            raise ValueError("turn exceeds the canvas transaction limit")
        cue_ids = [cue.id for cue in cues]
        if len(cue_ids) != len(set(cue_ids)):
            raise ValueError("canvas cue ids must be unique across the turn")

        canvas_complexity = CanvasComplexity(self.canvas_decision.complexity)
        if canvas_complexity == CanvasComplexity.NONE and cues:
            raise ValueError("canvasDecision=none cannot contain canvas cues")
        if canvas_complexity == CanvasComplexity.NORMAL and not cues:
            raise ValueError("canvasDecision=normal requires canvas cues")
        if canvas_complexity == CanvasComplexity.SPECIALIST_REQUIRED and cues:
            raise ValueError(
                "specialistRequired defers canvas transactions to the specialist"
            )

        revisions: dict[str, int] = defaultdict(int)
        created_node_count = 0
        for cue in cues:
            transaction = cue.transaction
            expected_base = revisions[transaction.scene_id]
            if transaction.base_revision != expected_base:
                raise ValueError(
                    f"scene {transaction.scene_id} expected baseRevision "
                    f"{expected_base}, got {transaction.base_revision}"
                )
            revisions[transaction.scene_id] = transaction.revision
            created_node_count += sum(
                isinstance(operation, CanvasCreateOperation)
                for operation in transaction.operations
            )
        if created_node_count > CANVAS_MAX_NODES_PER_TURN:
            raise ValueError("turn exceeds the canvas node creation limit")
        return self

    @property
    def speech(self) -> str:
        return " ".join(segment.speech for segment in self.segments)


def _substring_positions(text: str, phrase: str) -> tuple[int, ...]:
    positions: list[int] = []
    start = 0
    while True:
        index = text.find(phrase, start)
        if index < 0:
            return tuple(positions)
        positions.append(index)
        start = index + max(1, len(phrase))
